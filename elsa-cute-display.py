    def on_toggle_theme(self, _btn):
        self.dark_mode = not self.dark_mode
        if self.dark_mode:
            self.style_manager.set_color_scheme(Adw.ColorScheme.FORCE_DARK)
            self.theme_btn.set_label("☀️ Light")
        else:
            self.style_manager.set_color_scheme(Adw.ColorScheme.FORCE_LIGHT)
            self.theme_btn.set_label("🌙 Dark")

    def on_quick_dropdown_changed(self, dropdown, _pspec):
        if self._updating_dropdown:
            return
        idx = dropdown.get_selected()
        if idx == 0 or idx > len(self._profile_files):
            return
        fname = self._profile_files[idx - 1]
        full_path = os.path.join(PROFILES_DIR, fname)
        self.on_apply_profile(None, full_path)

        # Reset dropdown to placeholder so user can easily re-apply the same profile later
        def reset_dd():
            self._updating_dropdown = True
            self.quick_dropdown.set_selected(0)
            self._updating_dropdown = False
            return False

        GLib.idle_add(reset_dd)

    def on_capture_save_as(self, _btn):
        try:
            serials, logicals = parse_gdctl_show()
            if not logicals:
                self.status_lbl.set_label("⚠️ No active monitors detected by gdctl.")
                return
            self._pending_script = build_shell_script(serials, logicals)
        except Exception as e:
            self.status_lbl.set_label(f"⚠️ Error reading monitors: {e}")
            return

        dialog = Gtk.FileDialog()
        dialog.set_title("Save Monitor Profile As...")
        dialog.set_initial_folder(Gio.File.new_for_path(PROFILES_DIR))
        dialog.set_initial_name("my-dock-setup.sh")
        dialog.save(self, None, self.on_save_dialog_done)

    def on_save_dialog_done(self, dialog, result):
        try:
            gfile = dialog.save_finish(result)
            if not gfile:
                return
            path = gfile.get_path()
            if not path.endswith(".sh"):
                path += ".sh"
            with open(path, "w", encoding="utf-8") as f:
                f.write(self._pending_script)
            os.chmod(path, os.stat(path).st_mode | stat.S_IEXEC)
            self.status_lbl.set_label(f"✨ Saved profile: {os.path.basename(path)} — ready to Apply or bind!")
            self.refresh_profiles()
        except Exception as e:
            if "Dismissed" not in str(e):
                self.status_lbl.set_label(f"⚠️ Save failed: {e}")

    def refresh_profiles(self):
        child = self.profiles_box.get_first_child()
        while child:
            next_child = child.get_next_sibling()
            self.profiles_box.remove(child)
            child = next_child

        self._profile_files = sorted(f for f in os.listdir(PROFILES_DIR) if f.endswith(".sh"))

        # Update Quick-Apply Dropdown
        self._updating_dropdown = True
        if self._profile_files:
            dd_items = ["🌸 Select a profile to apply instantly..."] + [f"🖥️  {f}" for f in self._profile_files]
            self.quick_dropdown.set_sensitive(True)
        else:
            dd_items = ["🌸 Awaiting your first saved .sh profile..."]
            self.quick_dropdown.set_sensitive(False)
        self.quick_dropdown.set_model(Gtk.StringList.new(dd_items))
        self.quick_dropdown.set_selected(0)
        self._updating_dropdown = False

        if not self._profile_files:
            empty = Gtk.Label(label="🌸 Awaiting your first saved .sh profile... Follow [1] & [2] above!")
            empty.add_css_class("dim-label")
            empty.set_margin_top(20)
            self.profiles_box.append(empty)
            return

        for fname in self._profile_files:
            full_path = os.path.join(PROFILES_DIR, fname)
            row = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=8)
            row.add_css_class("profile-row")

            lbl = Gtk.Label(label=f"🖥️  {fname}", xalign=0)
            lbl.set_hexpand(True)
            row.append(lbl)

            apply_btn = Gtk.Button(label="Apply")
            apply_btn.add_css_class("suggested-action")
            apply_btn.connect("clicked", self.on_apply_profile, full_path)
            row.append(apply_btn)

            key_btn = Gtk.Button(label="⌨️ Shortcut")
            key_btn.connect("clicked", self.on_shortcut_dialog, fname, full_path)
            row.append(key_btn)

            del_btn = Gtk.Button(label="🗑️")
            del_btn.add_css_class("destructive-action")
            del_btn.connect("clicked", self.on_delete_profile, full_path)
            row.append(del_btn)

            self.profiles_box.append(row)

    def on_apply_profile(self, _btn, path):
        try:
            subprocess.run([path], check=True)
            self.status_lbl.set_label(f"🌸 Applied: {os.path.basename(path)}")
        except Exception as e:
            self.status_lbl.set_label(f"⚠️ Failed to apply: {e}")

    def on_delete_profile(self, _btn, path):
        try:
            os.remove(path)
            self.status_lbl.set_label(f"🗑️ Deleted: {os.path.basename(path)}")
            self.refresh_profiles()
        except Exception as e:
            self.status_lbl.set_label(f"⚠️ Delete failed: {e}")

    def on_shortcut_dialog(self, _btn, fname, full_path):
        win = Adw.Window(transient_for=self, modal=True, title="Press Keyboard Shortcut")
        win.set_default_size(400, 220)

        captured = {"binding": "", "label": ""}

        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=14)
        box.set_margin_top(20)
        box.set_margin_bottom(20)
        box.set_margin_start(20)
        box.set_margin_end(20)

        lbl = Gtk.Label(label=f"⌨️ Press your desired shortcut keys for:\n{fname}", xalign=0)
        box.append(lbl)

        capture_lbl = Gtk.Label(label="Listening... Press keys now (e.g. Ctrl+Alt+4)")
        capture_lbl.add_css_class("key-capture-box")
        box.append(capture_lbl)

        btn_box = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=8)
        btn_box.set_halign(Gtk.Align.END)

        cancel_btn = Gtk.Button(label="Cancel")
        cancel_btn.connect("clicked", lambda *_: win.close())
        btn_box.append(cancel_btn)

        save_btn = Gtk.Button(label="Save Shortcut")
        save_btn.add_css_class("suggested-action")
        save_btn.set_sensitive(False)
        btn_box.append(save_btn)
        box.append(btn_box)

        key_ctrl = Gtk.EventControllerKey()

        def on_key_pressed(_ctrl, keyval, _keycode, state):
            if keyval == Gdk.KEY_Escape:
                win.close()
                return True
            if keyval in MODIFIER_KEYS:
                return True

            mods = state & Gtk.accelerator_get_default_mod_mask()
            is_fkey = (Gdk.KEY_F1 <= keyval <= Gdk.KEY_F12)
            if not mods and not is_fkey:
                capture_lbl.set_label("⚠️ Include Ctrl, Alt, or Super!")
                save_btn.set_sensitive(False)
                return True

            binding = Gtk.accelerator_name(keyval, mods)
            pretty = Gtk.accelerator_get_label(keyval, mods)
            captured["binding"] = binding
            captured["label"] = pretty
            capture_lbl.set_label(f"✨ {pretty}")
            save_btn.set_sensitive(True)
            return True

        key_ctrl.connect("key-pressed", on_key_pressed)
        win.add_controller(key_ctrl)

        def finalize_save(clear_path=None):
            try:
                set_gnome_shortcut(f"Elsa-Cute-Display: {fname}", full_path, captured["binding"], clear_path)
                self.status_lbl.set_label(f"⌨️ Shortcut {captured['label']} bound to {fname}!")
                win.close()
            except Exception as e:
                self.status_lbl.set_label(f"⚠️ Shortcut error: {e}")

        def show_duplicate_prompt(conflict_name, conflict_path):
            warn = Adw.Window(transient_for=win, modal=True, title="Duplicate Shortcut")
            warn.set_default_size(380, 170)

            wbox = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=14)
            wbox.set_margin_top(20)
            wbox.set_margin_bottom(20)
            wbox.set_margin_start(20)
            wbox.set_margin_end(20)

            wlbl = Gtk.Label(
                label=f"⚠️ '{captured['label']}' is already used by:\n\"{conflict_name}\"\n\nDo you want to overwrite it?",
                xalign=0, wrap=True
            )
            wbox.append(wlbl)

            wbtns = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=8)
            wbtns.set_halign(Gtk.Align.END)

            no_btn = Gtk.Button(label="No, Choose Another")
            no_btn.connect("clicked", lambda *_: warn.close())
            wbtns.append(no_btn)

            yes_btn = Gtk.Button(label="Yes, Overwrite")
            yes_btn.add_css_class("destructive-action")

            def on_yes(_b):
                warn.close()
                finalize_save(clear_conflict_path=conflict_path)

            yes_btn.connect("clicked", on_yes)
            wbtns.append(yes_btn)
            wbox.append(wbtns)

            warn.set_content(wbox)
            warn.present()

        def on_save_clicked(_b):
            if not captured["binding"]:
                return
            conflict_name, conflict_path = find_duplicate_shortcut(captured["binding"], full_path)
            if conflict_path:
                show_duplicate_prompt(conflict_name, conflict_path)
            else:
                finalize_save()

        save_btn.connect("clicked", on_save_clicked)
        win.set_content(box)
        win.present()


