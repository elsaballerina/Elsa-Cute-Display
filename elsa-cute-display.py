def parse_gdctl_show():
    out = subprocess.check_output(["gdctl", "show"], text=True)
    serials = {}
    current_conn = None
    in_logical = False

    for line in out.splitlines():
        if line.strip().startswith("Logical monitors:"):
            in_logical = True
            break
        m_conn = re.search(r"Monitor\s+(\S+)", line)
        if m_conn:
            current_conn = m_conn.group(1)
        m_ser = re.search(r"Serial:\s+(\S+)", line)
        if m_ser and current_conn:
            serials[current_conn] = m_ser.group(1)

    logicals = []
    current = None
    in_monitors_block = False
    for line in out.splitlines():
        if line.strip().startswith("Logical monitors:"):
            in_logical = True
            continue
        if not in_logical:
            continue

        if "Logical monitor #" in line:
            if current:
                logicals.append(current)
            current = {
                "x": 0, "y": 0, "scale": "1.0",
                "transform": "normal", "primary": False, "monitors": []
            }
            in_monitors_block = False
            continue

        if not current:
            continue

        m_pos = re.search(r"Position:\s+\((-?\d+),\s*(-?\d+)\)", line)
        if m_pos:
            current["x"], current["y"] = int(m_pos.group(1)), int(m_pos.group(2))
        m_scale = re.search(r"Scale:\s+([0-9.]+)", line)
        if m_scale:
            current["scale"] = m_scale.group(1)
        m_trans = re.search(r"Transform:\s+(\S+)", line)
        if m_trans:
            current["transform"] = m_trans.group(1)
        m_prim = re.search(r"Primary:\s+(yes|no)", line)
        if m_prim:
            current["primary"] = (m_prim.group(1) == "yes")
        if "Monitors:" in line:
            in_monitors_block = True
            continue
        if in_monitors_block:
            m_mon = re.search(r"[└├]──(\S+)", line)
            if m_mon:
                current["monitors"].append(m_mon.group(1))

    if current:
        logicals.append(current)

    return serials, logicals


def build_shell_script(serials, logicals):
    lines = [
        "#!/bin/bash",
        "# Generated by Elsa-Cute-Display v1.0",
        "",
        "get_conn() {",
        "  gdctl show | awk -v ser=\"$1\" '",
        "    /Monitor / { conn = $2 }",
        "    $0 ~ \"Serial: \" ser { print conn; exit }",
        "  '",
        "}",
        ""
    ]

    cmd_parts = ["gdctl set --persistent"]
    var_idx = 1

    for lm in logicals:
        mon_flags = []
        for conn in lm["monitors"]:
            ser = serials.get(conn, "")
            if ser and ser != "0x00000000":
                var_name = f"MON_{var_idx}"
                var_idx += 1
                lines.append(f'{var_name}=$(get_conn "{ser}")  # {conn}')
                mon_flags.append(f'--monitor "${var_name}"')
            else:
                mon_flags.append(f'--monitor "{conn}"')

        part = "--logical-monitor"
        if lm["primary"]:
            part += " --primary"
        part += f' --x {lm["x"]} --y {lm["y"]} --scale {lm["scale"]} --transform {lm["transform"]} ' + " ".join(mon_flags)
        cmd_parts.append(part)

    lines.append("")
    lines.append(" \\\n  ".join(cmd_parts))
    lines.append("")
    return "\n".join(lines)


def get_custom_keybindings():
    base = "org.gnome.settings-daemon.plugins.media-keys"
    raw = subprocess.check_output(["gsettings", "get", base, "custom-keybindings"], text=True).strip()
    return re.findall(r"'([^']+)'", raw)


def find_duplicate_shortcut(binding, current_command):
    base = "org.gnome.settings-daemon.plugins.media-keys"
    for p in get_custom_keybindings():
        schema_path = f"{base}.custom-keybinding:{p}"
        b = subprocess.check_output(["gsettings", "get", schema_path, "binding"], text=True).strip().strip("'")
        cmd = subprocess.check_output(["gsettings", "get", schema_path, "command"], text=True).strip().strip("'")
        if b.lower() == binding.lower() and cmd != current_command:
            name = subprocess.check_output(["gsettings", "get", schema_path, "name"], text=True).strip().strip("'")
            return name, p
    return None, None


def set_gnome_shortcut(name, command, binding, clear_conflict_path=None):
    base = "org.gnome.settings-daemon.plugins.media-keys"
    paths = get_custom_keybindings()

    if clear_conflict_path:
        subprocess.run(["gsettings", "set", f"{base}.custom-keybinding:{clear_conflict_path}", "binding", ""], check=True)

    target_path = None
    for p in paths:
        schema_path = f"{base}.custom-keybinding:{p}"
        cmd = subprocess.check_output(["gsettings", "get", schema_path, "command"], text=True).strip().strip("'")
        if cmd == command:
            target_path = p
            break

    if not target_path:
        idx = 0
        while f"/org/gnome/settings-daemon/plugins/media-keys/custom-keybindings/custom{idx}/" in paths:
            idx += 1
        target_path = f"/org/gnome/settings-daemon/plugins/media-keys/custom-keybindings/custom{idx}/"
        paths.append(target_path)

    schema_path = f"{base}.custom-keybinding:{target_path}"
    subprocess.run(["gsettings", "set", schema_path, "name", name], check=True)
    subprocess.run(["gsettings", "set", schema_path, "command", command], check=True)
    subprocess.run(["gsettings", "set", schema_path, "binding", binding], check=True)

    list_str = "[" + ", ".join(f"'{p}'" for p in paths) + "]"
    subprocess.run(["gsettings", "set", base, "custom-keybindings", list_str], check=True)


